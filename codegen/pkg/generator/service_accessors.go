package generator

import (
	"bytes"
	"fmt"
	"maps"
	"os"
	"path/filepath"
	"slices"

	"github.com/iancoleman/strcase"
)

// writeServiceAccessors keeps the generated API groups separate from the hand-written client.
func (g *Generator) writeServiceAccessors() error {
	var services []string
	for _, tagKey := range slices.Sorted(maps.Keys(g.operationsByTag)) {
		if g.shouldIncludeService(tagKey, g.operationsByTag[tagKey]) {
			services = append(services, g.displayTagName(tagKey))
		}
	}

	var buf bytes.Buffer
	buf.WriteString("<?php\n\n// Code generated by sumup-php/codegen. DO NOT EDIT.\nnamespace SumUp;\n\n")
	for _, service := range services {
		fmt.Fprintf(&buf, "use SumUp\\Services\\%s;\n", service)
	}
	buf.WriteString("\n/** API groups available through the SumUp client. */\ntrait ServiceAccessors\n{\n")
	for i, service := range services {
		if i > 0 {
			buf.WriteString("\n")
		}
		buf.WriteString("    /**\n")
		fmt.Fprintf(&buf, "     * Access the %s API endpoints.\n", service)
		buf.WriteString("     */\n")
		fmt.Fprintf(&buf, "    public function %s(): %s\n", strcase.ToLowerCamel(service), service)
		buf.WriteString("    {\n")
		fmt.Fprintf(&buf, "        return new %s($this->client, $this->resolveAccessToken());\n", service)
		buf.WriteString("    }\n")
	}
	buf.WriteString("}\n")

	filename := filepath.Join(g.cfg.Out, "ServiceAccessors.php")
	if err := os.WriteFile(filename, buf.Bytes(), 0o644); err != nil {
		return fmt.Errorf("write service accessors: %w", err)
	}
	return nil
}
