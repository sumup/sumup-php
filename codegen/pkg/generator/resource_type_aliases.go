package generator

import (
	"fmt"
	"maps"
	"os"
	"path/filepath"
	"slices"
	"strings"
)

func (g *Generator) resourceTypeNamespace(tag string) string {
	if parent := g.resourceParents[tag]; parent.tag != "" {
		return g.resourceTypeNamespace(parent.tag) + "\\" + sanitizeTagName(parent.label)
	}
	return typesNamespace + "\\" + g.displayTagName(tag)
}

// Composer loads these aliases even when its classmap is authoritative.
func (g *Generator) writeResourceTypeAliases() error {
	var b strings.Builder
	b.WriteString("<?php\n\ndeclare(strict_types=1);\n\n// Code generated by sumup-php/codegen. DO NOT EDIT.\n")
	for _, name := range slices.Sorted(maps.Keys(g.resourceSchemaUsage)) {
		if g.schemaNamespaces[name] != typesNamespace {
			continue
		}
		for _, tag := range slices.Sorted(maps.Keys(g.resourceSchemaUsage[name].tags)) {
			if g.resourceParents[tag].tag != "" {
				fmt.Fprintf(&b, "\nclass_alias(\\%s\\%s::class, \\%s\\%s::class);\n", typesNamespace, name, g.resourceTypeNamespace(tag), name)
			}
		}
	}
	if err := os.WriteFile(filepath.Join(g.cfg.Out, "ResourceTypeAliases.php"), []byte(b.String()), 0o644); err != nil {
		return fmt.Errorf("write resource type aliases: %w", err)
	}
	return nil
}
